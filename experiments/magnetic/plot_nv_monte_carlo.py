
"""Plot reproducible NV magnetometry Monte Carlo results.

Reads CSV files generated by nv_monte_carlo_performance.py.
Does not rerun Monte Carlo simulations.

Run from the repository root:
    .\\.venv\\Scripts\\python.exe experiments/magnetic/plot_nv_monte_carlo.py
"""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np

RESULTS_DIR = Path("experiments/magnetic/results")
FIGURES_DIR = RESULTS_DIR / "figures"


def read_csv(path: Path) -> list[dict[str, str]]:
    """Read a CSV file as dictionaries."""
    with path.open(newline="", encoding="utf-8") as file:
        return list(csv.DictReader(file))


def main() -> None:
    """Generate three scientific figures from saved experiment data."""

    summary = read_csv(RESULTS_DIR / "nv_monte_carlo_summary.csv")
    trials = read_csv(RESULTS_DIR / "nv_monte_carlo_trials.csv")

    if not summary or not trials:
        raise ValueError("Monte Carlo result files must not be empty")

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    summary.sort(key=lambda row: float(row["reference_photon_count"]))

    photons = np.asarray(
        [float(row["reference_photon_count"]) for row in summary]
    )
    rmse = np.asarray([float(row["rmse_nt"]) for row in summary])
    crlb = np.asarray(
        [float(row["theoretical_crlb_nt"]) for row in summary]
    )
    empirical_std = np.asarray(
        [float(row["empirical_std_nt"]) for row in summary]
    )

    # Figure 1: Empirical RMSE and theoretical CRLB.
    fig, ax = plt.subplots(figsize=(8, 5))

    ax.plot(photons, rmse, "o-", label="Empirical RMSE")
    ax.plot(photons, crlb, "s--", label="Theoretical CRLB")

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Reference photons per frequency sample")
    ax.set_ylabel("Magnetic-field uncertainty / error (nT)")
    ax.set_title("BQRC NV Magnetometry: RMSE vs CRLB")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()

    fig.tight_layout()
    figure_1 = FIGURES_DIR / "nv_rmse_vs_crlb.png"
    fig.savefig(figure_1, dpi=200)
    plt.close(fig)

    # Figure 2: Empirical standard deviation and 1/sqrt(N) scaling.
    reference_scaling = empirical_std[0] * np.sqrt(photons[0] / photons)

    fig, ax = plt.subplots(figsize=(8, 5))

    ax.plot(
        photons,
        empirical_std,
        "o-",
        label="Empirical standard deviation",
    )
    ax.plot(
        photons,
        reference_scaling,
        "s--",
        label="1/sqrt(N) reference",
    )

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Reference photons per frequency sample")
    ax.set_ylabel("Empirical standard deviation (nT)")
    ax.set_title("BQRC NV Magnetometry: Photon-Count Scaling")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()

    fig.tight_layout()
    figure_2 = FIGURES_DIR / "nv_photon_scaling.png"
    fig.savefig(figure_2, dpi=200)
    plt.close(fig)

    # Figure 3: Individual estimation errors at each photon budget.
    grouped_errors: dict[float, list[float]] = defaultdict(list)

    for row in trials:
        photon_count = float(row["reference_photon_count"])
        grouped_errors[photon_count].append(float(row["error_nt"]))

    budgets = sorted(grouped_errors)

    fig, ax = plt.subplots(figsize=(8, 5))

    for photon_count in budgets:
        errors = np.asarray(grouped_errors[photon_count])

        ax.hist(
            errors,
            bins=12,
            alpha=0.45,
            label=f"{photon_count:,.0f} photons",
        )

    ax.axvline(0.0, linestyle="--", color="black", label="Zero error")
    ax.set_xlabel("Estimated field minus true field (nT)")
    ax.set_ylabel("Number of Monte Carlo trials")
    ax.set_title("BQRC NV Magnetometry: Estimation Error Distributions")
    ax.grid(True, alpha=0.25)
    ax.legend()

    fig.tight_layout()
    figure_3 = FIGURES_DIR / "nv_error_distributions.png"
    fig.savefig(figure_3, dpi=200)
    plt.close(fig)

    print("=" * 72)
    print("BQRC NV MAGNETOMETRY — SCIENTIFIC VISUALIZATION")
    print("=" * 72)
    print(f"Photon budgets analyzed : {len(budgets)}")
    print(f"Trial records analyzed  : {len(trials)}")
    print()
    print("Generated figures:")
    print(f"  1. {figure_1}")
    print(f"  2. {figure_2}")
    print(f"  3. {figure_3}")
    print("=" * 72)


if __name__ == "__main__":
    main()
